/**
 * Gmail auto-reply for Atomic Consulting & Solutions (Google Apps Script). Free; no AI, no API keys.
 *
 * Every few minutes it reads new emails in your inbox and replies with the same answers as the website
 * chatbot: prices, services, "I already have a website…", buying questions and more, one section for
 * each thing the email asks about. Emails showing they're ready to buy are starred and labelled
 * "Auto-reply/Hot lead". Newsletters, no-reply senders and threads you've already answered are skipped.
 *
 * SETUP (about 5 minutes)
 *   1. Go to https://script.google.com while signed in to the Gmail account it should answer from.
 *   2. New project → delete the sample code → paste this whole file → rename the project "Auto-reply".
 *   3. Edit SETTINGS below if you like. Leave MODE as 'draft' for now.
 *   4. Pick `testReply` in the function dropdown at the top and press Run. Google asks for permission
 *      the first time (Advanced → Go to Auto-reply → Allow). The log shows the reply it would send to
 *      TEST_EMAIL. Change TEST_EMAIL and run it again to try other emails.
 *   5. Pick `install` and press Run. From now on it checks your inbox every few minutes.
 *   6. For a few days, check the drafts it writes (Gmail → Drafts). When you're happy, change MODE to
 *      'send' and save. Run `uninstall` at any time to stop it.
 *
 * Gmail labels show what it did: "Auto-reply/Replied", "Auto-reply/Skipped" and "Auto-reply/Hot lead".
 * Google lets a free Gmail account send about 100 emails a day from scripts (1,500 with Workspace).
 *
 * THIS FILE IS GENERATED by `npm run build:email` from email-agent/gmail.js and the website chatbot
 * (src/chatbot). To change what it says, edit the chatbot and rebuild; SETTINGS can be edited either here
 * after pasting or in email-agent/gmail.js.
 */

// ─────────────────────────────── SETTINGS ───────────────────────────────

var SETTINGS = {
  MODE: 'send',                  // 'send' = send replies automatically; 'draft' = write them as drafts for you to check and send
  CHECK_EVERY_MINUTES: 5,        // 1, 5, 10, 15 or 30
  MAX_TOPICS_PER_REPLY: 3,       // answer up to this many things from one email
  REPLY_ONCE_PER_HOURS: 24,      // never auto-reply to the same person more often than this
  STAR_HOT_LEADS: true,          // star emails from people ready to buy or asking about prices

  GREETING: 'Hi {name},',        // {name} = sender's first name, or "there" if unknown
  INTRO: 'Thanks for reaching out to Atomic Consulting & Solutions! This is an automatic reply with some quick info while Patrick reviews your message:',
  OUTRO: "Patrick will follow up personally within 24 hours. If you'd like to talk sooner, just reply with a good time for a free, no-obligation scoping call.",
  SIGNATURE: 'Atomic Consulting & Solutions\nhttps://atomicconsulting.org',
  SENDER_NAME: 'Patrick Tomic | Atomic Consulting & Solutions',
  SITE_URL: 'https://atomicconsulting.org',

  // When nothing in the email matches a topic
  FALLBACK: "Thanks for your email! Patrick has received it and will get back to you personally within 24 hours.",
  // Added after "Great, let's get your website going!" when someone is ready to buy
  BUY_NEXT_STEPS: "To put together an accurate quote, just reply with what you need, your timeline, and the best phone number to reach you. Patrick will confirm everything, including payment, before any work begins.",
  // When the email is a complaint: no sales pitch
  FRUSTRATED: "Thanks for your message, and sorry for any trouble. Patrick will read it personally and get back to you as soon as possible.",

  // Senders and subjects that never get an auto-reply
  SKIP_SENDERS: ['noreply', 'no-reply', 'donotreply', 'do-not-reply', 'mailer-daemon', 'postmaster', 'notifications', 'newsletter', 'bounce'],
  SKIP_SUBJECTS: ['unsubscribe', 'out of office', 'automatic reply', 'auto-reply', 'autoreply', 'delivery status', 'undeliverable', 'receipt', 'invoice #', 'order confirmation', 'verify your'],
}

// Sample email for testReply()
var TEST_EMAIL = {
  from: 'Jane Smith <jane@example.com>',
  subject: 'Website for my bakery',
  body: "Hi, I own a small bakery and need a website with about 4 pages. How much would that cost and how long does it take? Thanks!",
}

// ───────────────────────── Triggers (run these by hand) ─────────────────────────

function install() {
  uninstall()
  ScriptApp.newTrigger('checkInbox').timeBased().everyMinutes(SETTINGS.CHECK_EVERY_MINUTES).create()
  getLabel_('Auto-reply/Replied')
  getLabel_('Auto-reply/Skipped')
  getLabel_('Auto-reply/Hot lead')
  console.log('Installed: checking the inbox every ' + SETTINGS.CHECK_EVERY_MINUTES + ' minutes in ' + SETTINGS.MODE + ' mode.')
}

function uninstall() {
  ScriptApp.getProjectTriggers()
    .filter(function (t) { return t.getHandlerFunction() === 'checkInbox' })
    .forEach(function (t) { ScriptApp.deleteTrigger(t) })
  console.log('Stopped: no automatic checks are scheduled.')
}

function testReply() {
  var result = AutoReply.composeReply(TEST_EMAIL, SETTINGS)
  console.log('Topics: ' + (result.topics.length ? result.topics.join(', ') : '(none, so the fallback reply is used)') +
    (result.hotLead ? '  ★ hot lead' : ''))
  console.log('Subject: Re: ' + TEST_EMAIL.subject + '\n\n' + result.reply)
}

// ───────────────────────────── Main loop ─────────────────────────────

function checkInbox() {
  var lock = LockService.getScriptLock()
  if (!lock.tryLock(1000)) return // a previous run is still going

  try {
    var replied = getLabel_('Auto-reply/Replied')
    var skipped = getLabel_('Auto-reply/Skipped')
    var hot = getLabel_('Auto-reply/Hot lead')
    var me = [Session.getEffectiveUser().getEmail()].concat(GmailApp.getAliases()).map(function (e) { return e.toLowerCase() })

    var query = 'in:inbox is:unread newer_than:2d -label:auto-reply-replied -label:auto-reply-skipped ' +
      '-category:promotions -category:social -category:updates -category:forums'
    var threads = GmailApp.search(query, 0, 30)

    for (var i = 0; i < threads.length; i++) {
      var thread = threads[i]
      var messages = thread.getMessages()
      var message = messages[messages.length - 1]
      var sender = AutoReply.emailAddress(message.getFrom())

      var reason = AutoReply.skipReason({
        sender: sender,
        subject: message.getSubject(),
        headers: {
          'List-Unsubscribe': message.getHeader('List-Unsubscribe'),
          'List-Id': message.getHeader('List-Id'),
          'Precedence': message.getHeader('Precedence'),
          'Auto-Submitted': message.getHeader('Auto-Submitted'),
        },
        me: me,
        threadSenders: messages.map(function (m) { return AutoReply.emailAddress(m.getFrom()) }),
        repliedRecently: repliedRecently_(sender),
      }, SETTINGS)
      if (reason) {
        thread.addLabel(skipped)
        console.log('Skipped "' + message.getSubject() + '" from ' + sender + ': ' + reason)
        continue
      }
      if (SETTINGS.MODE === 'send' && MailApp.getRemainingDailyQuota() < 1) {
        console.log('Daily sending limit reached; will try again tomorrow.')
        break
      }

      var result = AutoReply.composeReply({ from: message.getFrom(), subject: message.getSubject(), body: message.getPlainBody() }, SETTINGS)
      var options = { name: SETTINGS.SENDER_NAME }
      if (SETTINGS.MODE === 'send') message.reply(result.reply, options)
      else message.createDraftReply(result.reply, options)

      thread.addLabel(replied)
      if (result.hotLead) {
        thread.addLabel(hot)
        if (SETTINGS.STAR_HOT_LEADS) message.star()
      }
      rememberReply_(sender)
      console.log((SETTINGS.MODE === 'send' ? 'Replied to ' : 'Drafted reply to ') + sender +
        ' [' + (result.topics.join(', ') || 'fallback') + ']' + (result.hotLead ? ' ★ hot lead' : ''))
    }
    forgetOldReplies_()
  } finally {
    lock.releaseLock()
  }
}

// ───────────────────── Memory: who was answered recently ─────────────────────

function repliedRecently_(sender) {
  var at = Number(PropertiesService.getScriptProperties().getProperty('replied:' + sender))
  return Boolean(at) && Date.now() - at < SETTINGS.REPLY_ONCE_PER_HOURS * 3600 * 1000
}

function rememberReply_(sender) {
  PropertiesService.getScriptProperties().setProperty('replied:' + sender, String(Date.now()))
}

function forgetOldReplies_() {
  var props = PropertiesService.getScriptProperties()
  var cutoff = Date.now() - 7 * 24 * 3600 * 1000
  var all = props.getProperties()
  Object.keys(all).forEach(function (key) {
    if (key.indexOf('replied:') === 0 && Number(all[key]) < cutoff) props.deleteProperty(key)
  })
}

function getLabel_(name) {
  return GmailApp.getUserLabelByName(name) || GmailApp.createLabel(name)
}
