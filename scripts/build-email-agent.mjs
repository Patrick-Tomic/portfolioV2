// Builds email-agent/auto-reply.gs: the Gmail script (email-agent/gmail.js) plus the website chatbot's
// logic bundled into one file you can paste into Google Apps Script.
//
//   npm run build:email

import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'

const result = await build({
  entryPoints: ['email-agent/src/agent.ts'],
  bundle: true,
  format: 'iife',
  globalName: 'AutoReply', // gmail.js calls AutoReply.composeReply(...) etc.
  target: 'es2019', // Apps Script's V8 runtime
  write: false,
  legalComments: 'none',
})

const gmail = await readFile('email-agent/gmail.js', 'utf8')
const bundled = result.outputFiles[0].text

const output = `${gmail.trimEnd()}

// ─────────────────────────────────────────────────────────────────────────────
// Below: the website chatbot's understanding and answers (src/chatbot) and the email logic
// (email-agent/src/agent.ts), generated by \`npm run build:email\`. Don't edit by hand.
// ─────────────────────────────────────────────────────────────────────────────

${bundled}`

await writeFile('email-agent/auto-reply.gs', output)
console.log(`Wrote email-agent/auto-reply.gs (${Math.round(output.length / 1024)} KB). Paste it into your Apps Script project.`)
